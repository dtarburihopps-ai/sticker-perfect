// Sticker Perfect — отладочные сообщения
//
// Живут отдельным файлом, потому что ими пользуются все остальные:
// и звук, и меню, и движок. Раньше log() был объявлен в game.js, хотя
// звал его и sound.js, загружаемый раньше. Работало это по случайности —
// вызовы происходят позже загрузки, — но читалось как ошибка.

// Отладка включается адресом: ?debug=1 — и остаётся включённой при
// переходах между уровнями, progress.js её протаскивает.
//
// Раньше это была константа в коде, и она приехала на сайт включённой:
// игрок видел в консоли всю нашу кухню. А выключить её насовсем тоже
// нельзя — на телефоне консоль не открыть, и без сообщений непонятно,
// что вообще произошло.
const DEBUG = new URLSearchParams(location.search).has('debug');

function log() {
  if (DEBUG) console.log.apply(console, arguments);
}
